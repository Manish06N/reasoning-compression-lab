#!/usr/bin/env python3
"""Within-item spread of completion length across seeds, for every arm, as a LaTeX table (paper/generated/tab_lenvar.tex)."""
import json, sys
from pathlib import Path
import numpy as np

ROOT = Path(__file__).resolve().parents[3]
EXP = ROOT / "results" / "followup"
sys.path.insert(0, str(ROOT / "scripts" / "analysis")); sys.path.insert(0, str(Path(__file__).resolve().parent))
import revision_sensitivities as rs, seed_placebo as sp

B = 10_000
GEN = ROOT / "paper" / "v2_followups" / "generated"; OUT = EXP / "reports"; GEN.mkdir(parents=True, exist_ok=True); OUT.mkdir(exist_ok=True)


def ld(folder, stem, seeds):
    return sp.load_compact([EXP / folder / f"{stem}_seed{s}.json" for s in seeds])[1]


def sgn(x): return f"{x:+.0f}"


rows, res = [], {}
for fam, stem in (("Qwen-7B", "DeepSeek-R1-Distill-Qwen-7B"), ("Llama-8B", "DeepSeek-R1-Distill-Llama-8B")):
    base = rs.load_cell("math500", fam, "BF16")[1].std(0, ddof=1)
    arms = [("BF16, campaign seeds 42--46", rs.load_cell("math500", fam, "BF16")[1]),
            ("BF16, held-out seeds 47--51 (placebo)", ld("revision3/compact/X1_heldout", f"{stem}_heldout_math500_n500", range(47, 52)))]
    arms += [(f, rs.load_cell("math500", fam, f)[1]) for f in ("FP8", "AWQ-4", "GPTQ-4")]
    arms += [("BF16 at \\texttt{float16}", ld("revision2/compact/E2_fp16", f"{stem}_fp16_math500_n500", range(42, 47))),
             ("BF16 at $T=0.8$", ld("revision2/compact/E3_T08", f"{stem}_T0.8_math500_n500", range(42, 47)))]
    if fam == "Llama-8B":
        arms.append(("Self-quantized AWQ-4", ld("revision2/compact/E1_awq", "DeepSeek-R1-Distill-Llama-8B-selfawq_math500_n500", range(42, 47))))
    idx = np.random.default_rng(0).integers(0, 500, (B, 500))
    rows.append(f"\\multicolumn{{4}}{{l}}{{\\emph{{{fam}}}}} \\\\")
    for k, (name, T) in enumerate(arms):
        s = T.std(0, ddof=1); d = s - base
        c = np.percentile(s[idx].mean(1), [2.5, 97.5]); dc = np.percentile(d[idx].mean(1), [2.5, 97.5])
        cell_d = "---" if k == 0 else f"\\vcell{{${sgn(d.mean())}$}}{{$[{sgn(dc[0])},{sgn(dc[1])}]$}}"
        rows.append(f"{name} & \\vcell{{${s.mean():.0f}$}}{{$[{c[0]:.0f},{c[1]:.0f}]$}} & {np.median(s):.0f} & {cell_d} \\\\")
        res[f"{fam} | {name}"] = dict(mean_sd=float(s.mean()), ci=[float(v) for v in c], median_sd=float(np.median(s)), diff=float(d.mean()), diff_ci=[float(v) for v in dc])
    rows.append("\\midrule")
rows.pop()

tex = ["% generated by analysis/gen_lenvar.py -- do not edit by hand", "\\begin{table}[t]", "\\centering",
       "\\caption{Within-item spread of completion length across seeds on MATH-500: for each item the standard deviation (tokens) over the five seeds, averaged over the 500 items, with item-level 95\\% intervals ($B=10{,}000$); the median item is in the third column. The last column is the paired item-level difference from the campaign BF16 seeds. The second BF16 row, five new seeds of the same unmodified model, shows how much this quantity moves with no modification at all.}",
       "\\label{tab:lenvar}", "\\small", "\\resizebox{\\linewidth}{!}{%", "\\begin{tabular}{lccc}", "\\toprule",
       "\\textbf{Arm} & \\vcell{\\textbf{Mean SD}}{(tokens)} & \\textbf{Median SD} & \\vcell{\\textbf{Mean SD}}{$-$ campaign BF16} \\\\", "\\midrule"] + rows + ["\\bottomrule", "\\end{tabular}%", "}", "\\end{table}", ""]
(GEN / "tab_lenvar.tex").write_text("\n".join(tex), encoding="utf-8")
(OUT / "lenvar.json").write_text(json.dumps(res, indent=1))
print("wrote tab_lenvar.tex")
