#!/usr/bin/env python3
"""Two consequences for published token-inflation designs.

(1) Noise floor of a single-run design: two runs of the SAME BF16 model, n random MATH-500 questions, the relative change in mean
    completion length (CTIR of Lian et al.), over all questions and within the questions the first run solved / failed.
(2) A placebo-free estimand: the item-matched difference in mean length of CORRECT runs (Proposition 2 of the paper), for every arm.

Writes analysis/outputs/noise_floor_crd.json and paper/generated/tab_noisefloor.tex, tab_crd.tex.
"""
import json, sys
from pathlib import Path
import numpy as np

ROOT = Path(__file__).resolve().parents[3]
EXP = V3 = ROOT / "results" / "followup"
sys.path.insert(0, str(ROOT / "scripts" / "analysis")); sys.path.insert(0, str(Path(__file__).resolve().parent))
import revision_sensitivities as rs, seed_placebo as sp

OUT = EXP / "reports"; OUT.mkdir(exist_ok=True)
GEN = ROOT / "paper" / "v2_followups" / "generated"; GEN.mkdir(parents=True, exist_ok=True)
FAMS = {"Qwen-7B": "DeepSeek-R1-Distill-Qwen-7B", "Llama-8B": "DeepSeek-R1-Distill-Llama-8B"}
rng = np.random.default_rng(2026)
res = {"noise_floor": {}, "crd": {}}


def sgn(x, d=0):
    s = f"{abs(x):.{d}f}"
    return ("+" if x >= 0 and float(s) != 0 else "-" if x < 0 and float(s) != 0 else "") + s


# ------------------------------------------------------------------ (1) noise floor
def ctir(l_ref, l_oth, mask):
    if mask.sum() < 4: return np.nan
    return (l_oth[mask].mean() - l_ref[mask].mean()) / l_ref[mask].mean() * 100


def noise_floor(A, T, n, R):
    S, N = A.shape
    out = {"all": [], "correct": [], "wrong": []}
    if n == N: draws = [(s, t, np.arange(N)) for s in range(S) for t in range(S) if s != t]
    else: draws = []
    for r in range(R if n < N else 0):
        s, t = rng.choice(S, 2, replace=False); draws.append((s, t, rng.choice(N, n, replace=False)))
    for s, t, idx in draws:
        a, l1, l2 = A[s][idx], T[s][idx], T[t][idx]
        out["all"].append(ctir(l1, l2, np.ones(len(idx), bool))); out["correct"].append(ctir(l1, l2, a == 1)); out["wrong"].append(ctir(l1, l2, a == 0))
    return {k: np.array(v) for k, v in out.items()}


rows_nf = []
for fam in FAMS:
    A, T = rs.load_cell("math500", fam, "BF16")
    for n, R in ((100, 20000), (500, 0)):
        d = noise_floor(A, T, n, R); res["noise_floor"].setdefault(fam, {})[str(n)] = {}
        for sub in ("all", "correct", "wrong"):
            x = d[sub]; x = x[~np.isnan(x)]
            lo, hi = (float(np.percentile(x, 2.5)), float(np.percentile(x, 97.5))) if n < 500 else (float(x.min()), float(x.max()))
            rec = dict(mean=float(x.mean()), ci=[lo, hi], p5=float(np.mean(x > 5) * 100), p10=float(np.mean(x > 10) * 100), n_draws=int(len(x)))
            res["noise_floor"][fam][str(n)][sub] = rec
            rows_nf.append((fam, n, sub, rec))

label = {"all": "all questions", "correct": "questions run 1 solved", "wrong": "questions run 1 failed"}
L = ["% generated by analysis/noise_floor_crd.py -- do not edit by hand", "\\begin{table}[t]", "\\centering",
     "\\caption{Noise floor of a single-run design: two runs of the \\emph{same} BF16 model, $n$ random MATH-500 questions, and the relative change in mean completion length of run 2 against run 1 (the ``token inflation ratio'' of Lian et al., in percent), over all questions and within the questions run 1 solved or failed. For $n=100$: 20{,}000 random draws of two seeds and 100 questions (95\\% range of the draws); for $n=500$: all 20 ordered pairs of the five seeds (min--max). Last two columns: share of draws with an apparent inflation above $5\\%$ and $10\\%$. No quantization is involved.}",
     "\\label{tab:noisefloor}", "\\small", "\\resizebox{\\linewidth}{!}{%", "\\begin{tabular}{llcccc}", "\\toprule",
     "\\textbf{Family, $n$} & \\textbf{Subset} & \\textbf{Mean (\\%)} & \\textbf{Range (\\%)} & $P(>5\\%)$ & $P(>10\\%)$ \\\\", "\\midrule"]
prev = None
for fam, n, sub, r in rows_nf:
    if (fam, n) != prev and prev is not None: L.append("\\midrule")
    head = (fam + ", $n=" + str(n) + "$") if (fam, n) != prev else ""
    L.append(f"{head} & {label[sub]} & ${sgn(r['mean'], 1)}$ & $[{sgn(r['ci'][0], 1)},{sgn(r['ci'][1], 1)}]$ & {r['p5']:.0f}\\% & {r['p10']:.0f}\\% \\\\")
    prev = (fam, n)
L += ["\\bottomrule", "\\end{tabular}%", "}", "\\end{table}", ""]
(GEN / "tab_noisefloor.tex").write_text("\n".join(L), encoding="utf-8")


# ------------------------------------------------------------------ (2) item-matched correct-run difference
def crd(Ab, Tb, Aq, Tq, B=10_000, seed=0):
    kb, kq = Ab.sum(0), Aq.sum(0); ok = (kb > 0) & (kq > 0)
    mb = (Ab * Tb).sum(0) / np.maximum(kb, 1); mq = (Aq * Tq).sum(0) / np.maximum(kq, 1)
    d = np.where(ok, mq - mb, 0.0); n = ok.astype(float)
    idx = np.random.default_rng(seed).integers(0, len(d), (B, len(d)))
    return float(d.sum() / n.sum()), [float(v) for v in np.percentile(d[idx].sum(1) / n[idx].sum(1), [2.5, 97.5])], int(n.sum())


def ld(g): return sp.load_compact(sorted(g))


arms = []
for fam, stem in FAMS.items():
    Ab, Tb = rs.load_cell("math500", fam, "BF16")
    An, Tn = ld((EXP / "revision3/compact/X1_heldout").glob(f"{stem}_heldout_math500_n500_seed*.json"))
    arms.append((fam, "BF16, seeds 47--51 (null)", Ab, Tb, An, Tn, False))
    for f in ("FP8", "AWQ-4", "GPTQ-4"):
        Aq, Tq = rs.load_cell("math500", fam, f); arms.append((fam, f, Ab, Tb, Aq, Tq, True))
    Af, Tf = ld((EXP / "revision2/compact/E2_fp16").glob(f"{stem}_fp16_math500_n500_seed*.json")); arms.append((fam, "BF16 at \\texttt{float16} (null)", Ab, Tb, Af, Tf, True))
    A8, T8 = ld((EXP / "revision2/compact/E3_T08").glob(f"{stem}_T0.8_math500_n500_seed*.json")); arms.append((fam, "BF16 at $T=0.8$", Ab, Tb, A8, T8, True))
    if fam == "Llama-8B":
        Ae, Te = ld((EXP / "revision2/compact/E1_awq").glob("DeepSeek-R1-Distill-Llama-8B-selfawq_math500_n500_seed4[2-6].json")); arms.append((fam, "Self-quantized AWQ-4, Marlin", Ab, Tb, Ae, Te, True))
        Ac, Tc = ld((V3 / "revision2/compact/E1c_awq_gemm").glob("*seed4[2-6].json")); arms.append((fam, "Self-quantized AWQ-4, GEMM", Ab, Tb, Ac, Tc, True))
    else:
        Ax, Tx = ld((V3 / "revision3/compact/X3_batch").glob("*seed4[2-6].json")); arms.append((fam, "BF16, batch limit 64 (null)", Ab, Tb, Ax, Tx, True))

L = ["% generated by analysis/noise_floor_crd.py -- do not edit by hand", "\\begin{table}[t]", "\\centering",
     "\\caption{Placebo-free estimand (Proposition~\\ref{prop:crd}): the item-matched difference in the mean length of \\emph{correct} runs, quantized (or modified) minus campaign BF16, averaged over the items solved at least once by both (tokens; item-level 95\\% intervals, $B=10{,}000$), with the number of items used. Rows marked (null) change nothing about the model, so the expected value is zero. For comparison, the cross-seed excess $\\Lambda_b-\\Pi_b$ of the same contrast (the BF16-seed row has no excess).}",
     "\\label{tab:crd}", "\\small", "\\resizebox{\\linewidth}{!}{%", "\\begin{tabular}{llccc}", "\\toprule",
     "\\textbf{Family} & \\textbf{Contrast} & \\vcell{\\textbf{Correct-run}}{\\textbf{difference}} & \\textbf{Items} & \\vcell{\\textbf{Cross-seed}}{\\textbf{excess}} \\\\", "\\midrule"]
prev = None
for fam, name, Ab, Tb, Aq, Tq, with_excess in arms:
    est, ci, n = crd(Ab, Tb, Aq, Tq)
    rec = dict(crd=est, crd_ci=ci, items=n)
    if with_excess:
        c = sp.compare(Ab, Tb, Aq, Tq, "cross", reps=10_000); rec.update(excess_cross=c["excess"], excess_cross_ci=c["excess_ci"])
    res["crd"][f"{fam} | {name}"] = rec
    if prev is not None and fam != prev: L.append("\\midrule")
    ex = "\\vcell{$%s$}{$[%s,%s]$}" % (sgn(rec["excess_cross"]), sgn(rec["excess_cross_ci"][0]), sgn(rec["excess_cross_ci"][1])) if with_excess else "---"
    L.append(f"{fam if fam != prev else ''} & {name} & \\vcell{{${sgn(est)}$}}{{$[{sgn(ci[0])},{sgn(ci[1])}]$}} & {n} & {ex} \\\\")
    prev = fam
L += ["\\bottomrule", "\\end{tabular}%", "}", "\\end{table}", ""]
(GEN / "tab_crd.tex").write_text("\n".join(L), encoding="utf-8")
(OUT / "noise_floor_crd.json").write_text(json.dumps(res, indent=1))
print("wrote noise_floor_crd.json, tab_noisefloor.tex, tab_crd.tex")
for fam, d in res["noise_floor"].items():
    for n, s in d.items(): print(fam, n, {k: (round(v["mean"], 1), [round(x, 1) for x in v["ci"]], round(v["p5"]), round(v["p10"])) for k, v in s.items()})
for k, v in res["crd"].items(): print(f"{k:55s} CRD {v['crd']:+6.0f} [{v['crd_ci'][0]:+5.0f},{v['crd_ci'][1]:+5.0f}] items {v['items']}" + (f"   excess {v['excess_cross']:+5.0f} [{v['excess_cross_ci'][0]:+4.0f},{v['excess_cross_ci'][1]:+4.0f}]" if 'excess_cross' in v else ""))
