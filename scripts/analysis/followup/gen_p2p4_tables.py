#!/usr/bin/env python3
"""LaTeX tables for the P2 self-quantized Qwen checkpoints and the P4 decoding-grid controls."""
import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
P2 = json.loads((REPO / "results" / "followup" / "reports" / "p2_qwen_results.json").read_text())
P4 = json.loads((REPO / "results" / "followup" / "reports" / "p4_decoding_results.json").read_text())
G2 = json.loads((REPO / "results" / "followup" / "reports" / "p2_qwen_gsm8k_results.json").read_text())
GEN = REPO / "paper" / "v2_followups" / "generated"; GEN.mkdir(parents=True, exist_ok=True)


def sgn(x, d=0):
    s = f"{abs(x):.{d}f}"
    return ("+" if x >= 0 and float(s) != 0 else "-" if x < 0 and float(s) != 0 else "") + s


def cell(v, ci, d=0): return "\\vcell{$%s$}{$[%s,%s]$}" % (sgn(v, d), sgn(ci[0], d), sgn(ci[1], d))


def row(name, r):
    cols = [name, cell(r["acc_pp"], r["acc_ci"], 2), cell(r["uncond"], r["uncond_ci"]), cell(r["lam"], r["lam_ci"]), cell(r["excess"], r["excess_ci"])]
    return " & ".join(cols) + " \\\\"


L = ["% generated by analysis/gen_p2p4_tables.py -- do not edit by hand", "\\begin{table}[t]", "\\centering",
     "\\caption{Qwen-7B checkpoints that we quantized ourselves, three independent calibration draws per method, against the campaign BF16 cells (seeds 42--44, seed-matched pairs; tokens; item-level 95\\% intervals, $B=10{,}000$). GPTQ-4 runs at \\texttt{bfloat16}, AWQ-4 at \\texttt{float16} on the GEMM kernel. Excess is $\\Lambda_b-\\Pi_b$ against the BF16 placebo of the same benchmark (five seeds on MATH-500, three on GSM8K, shown in each panel header). The community rows are the checkpoints of Table~\\ref{tab:placebo} (and of the GSM8K results) restricted to the same three seeds. Scored with the campaign scorer. The prompts of these runs lack the campaign's doubled beginning-of-sequence token (one token fewer on every MATH-500 item), which affects the contrast with campaign BF16 but not the comparisons among the self-quantized rows.}",
     "\\label{tab:p2qwen}", "\\small", "\\resizebox{\\linewidth}{!}{%", "\\begin{tabular}{lcccc}", "\\toprule",
     "\\textbf{Checkpoint} & \\vcell{\\textbf{pass@1}}{$\\Delta$ (pp)} & \\vcell{\\textbf{Unconditional}}{$\\overline{\\Delta\\ell}$} & \\vcell{\\textbf{BF16-correct}}{$\\Lambda_b$} & \\vcell{\\textbf{Excess}}{$\\Lambda_b-\\Pi_b$} \\\\", "\\midrule"]
for bi, (bench, D, plc) in enumerate((("MATH-500", P2, "+138 [+75,+207]"), ("GSM8K", G2, "+58 [+26,+97]"))):
    if bi: L.append("\\midrule")
    L.append("\\multicolumn{5}{l}{\\emph{%s (placebo %s)}} \\\\" % (bench, plc.replace("[", "$[").replace("]", "]$")))
    for m, nm in (("gptq4", "GPTQ-4"), ("awq4", "AWQ-4")):
        for c in range(3): L.append(row(f"Self-quantized {nm}, draw {c}", D[m][f"cal{c}"]))
        L.append(row(f"Self-quantized {nm}, three draws pooled", D[m]["pooled"])); L.append("\\cmidrule(lr){1-5}")
    L.append(row("Community GPTQ-4 (same seeds)", D["community_GPTQ-4"]))
    L.append(row("Community AWQ-4 (same seeds)", D["community_AWQ-4"]))
L += ["\\bottomrule", "\\end{tabular}%", "}", "\\end{table}", ""]
(GEN / "tab_p2qwen.tex").write_text("\n".join(L), encoding="utf-8")

NAMES = [("bf16_t0.2_b32k", "BF16, $T=0.2$, 32k"), ("bf16_t1.0_b32k", "BF16, $T=1.0$, 32k"), ("bf16_t0.6_b8k", "BF16, $T=0.6$, 8k"),
         ("bf16_t0.2_b8k", "BF16, $T=0.2$, 8k"), ("bf16_t1.0_b8k", "BF16, $T=1.0$, 8k"), None,
         ("awq_t0.6_b32k", "Self-quantized AWQ-4$^{\\dagger}$, $T=0.6$, 32k"), ("awq_t0.2_b32k", "AWQ-4$^{\\dagger}$, $T=0.2$, 32k"), ("awq_t1.0_b32k", "AWQ-4$^{\\dagger}$, $T=1.0$, 32k"),
         ("awq_t0.6_b8k", "AWQ-4$^{\\dagger}$, $T=0.6$, 8k"), ("awq_t0.2_b8k", "AWQ-4$^{\\dagger}$, $T=0.2$, 8k"), ("awq_t1.0_b8k", "AWQ-4$^{\\dagger}$, $T=1.0$, 8k")]
L = ["% generated by analysis/gen_p2p4_tables.py -- do not edit by hand", "\\begin{table}[t]", "\\centering",
     "\\caption{Real changes to the sampling setting, as positive controls for the placebo (Qwen-7B, 300 MATH-500 items, seeds 42--44, seed-matched pairs; tokens; item-level 95\\% intervals). Reference: the campaign BF16 cells at $T=0.6$ and a 32{,}768-token budget on the same items; the five-seed placebo on these items is $+121$ $[+47,+208]$. Settings differ in temperature $T$ and maximum new tokens (8k = 8{,}192, 32k = 32{,}768). The last column is the share of completions that stopped at the length limit. Pilot grid with one engine setting per cell; AWQ-4 is a self-quantized checkpoint on the GEMM kernel at \\texttt{float16}. $^{\\dagger}$The prompts of the AWQ-4 cells lack the campaign's doubled beginning-of-sequence token (one token fewer on every item); the BF16 rows use exactly the campaign's prompts.}",
     "\\label{tab:p4ctrl}", "\\small", "\\resizebox{\\linewidth}{!}{%", "\\begin{tabular}{lccccc}", "\\toprule",
     "\\textbf{Setting} & \\vcell{\\textbf{pass@1}}{$\\Delta$ (pp)} & \\vcell{\\textbf{Unconditional}}{$\\overline{\\Delta\\ell}$} & \\vcell{\\textbf{BF16-correct}}{$\\Lambda_b$} & \\vcell{\\textbf{Excess}}{$\\Lambda_b-\\Pi_b$} & \\textbf{Stops} \\\\", "\\midrule"]
for n in NAMES:
    if n is None: L.append("\\midrule"); continue
    k, label = n; r = P4[k]
    rr = dict(acc_pp=r["acc"], acc_ci=r["acc_ci"], uncond=r["uncond"], uncond_ci=r["uncond_ci"], lam=r["lam"], lam_ci=r["lam_ci"], excess=r["excess"], excess_ci=r["excess_ci"])
    L.append(row(label, rr)[:-3] + f" & {r['length_stop_share']*100:.1f}\\% \\\\")
L += ["\\bottomrule", "\\end{tabular}%", "}", "\\end{table}", ""]
(GEN / "tab_p4ctrl.tex").write_text("\n".join(L), encoding="utf-8")
print("wrote tab_p2qwen.tex, tab_p4ctrl.tex")
