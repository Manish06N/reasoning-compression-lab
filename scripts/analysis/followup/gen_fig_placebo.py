#!/usr/bin/env python3
"""Figure 1 as generated TikZ: BF16-correct conditional length change (filled) and unconditional change (open) with the
seed-placebo band, for the six quantized checkpoints (values as in Table 1), the float16 and T=0.8 controls, and the
self-quantized Llama AWQ-4. Writes paper/generated/fig_placebo.tex."""
import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
R = json.loads((REPO / "results" / "followup" / "reports" / "revision2_results.json").read_text())
OUT = REPO / "paper" / "v2_followups" / "generated" / "fig_placebo.tex"

# (conditional Lambda_b, CI, unconditional, CI) from Table 1 of the paper (campaign checkpoints, seed-matched pairs)
CAMP = {
    "Qwen-7B": {"placebo": (138, (75, 207)),
                "FP8": (172, (63, 291), -4, (-142, 134)), "AWQ-4": (390, (261, 531), 254, (116, 398)), "GPTQ-4": (326, (198, 464), 276, (121, 431))},
    "Llama-8B": {"placebo": (235, (151, 331)),
                 "FP8": (166, (33, 302), -106, (-284, 65)), "AWQ-4": (332, (182, 490), 80, (-109, 268)), "GPTQ-4": (417, (261, 583), 184, (12, 359))},
}
ROWS = {"GPTQ-4": 1, "AWQ-4": 2, "self": 3, "FP8": 4, "fp16": 5, "T08": 6, "placebo": 7}
LABELS = {1: "GPTQ-4", 2: "AWQ-4", 3: "\\shortstack{self-AWQ\\\\(Llama only)}", 4: "FP8", 5: "\\shortstack{BF16\\\\\\texttt{float16}}",
          6: "\\shortstack{BF16\\\\$T{=}0.8$}", 7: "\\shortstack{BF16\\\\placebo}"}


def bar(x0, x1, y, col):
    return [f"\\draw[{col}, thick] (axis cs:{x0:.0f},{y:.2f}) -- (axis cs:{x1:.0f},{y:.2f});",
            f"\\draw[{col}, thick] (axis cs:{x0:.0f},{y-0.08:.2f}) -- (axis cs:{x0:.0f},{y+0.08:.2f});",
            f"\\draw[{col}, thick] (axis cs:{x1:.0f},{y-0.08:.2f}) -- (axis cs:{x1:.0f},{y+0.08:.2f});"]


def panel(fam):
    L = []
    pl, pci = CAMP[fam]["placebo"]
    L.append(f"\\fill[gray!22] (axis cs:{pci[0]},0.4) rectangle (axis cs:{pci[1]},7.6);")
    L.append("\\draw[gray!70, dashed] (axis cs:0,0.4) -- (axis cs:0,7.6);")
    pts_b, pts_r = [], []
    arms = []
    for k in ("FP8", "AWQ-4", "GPTQ-4"):
        lam, lci, un, uci = CAMP[fam][k]; arms.append((ROWS[k], lam, lci, un, uci))
    for key, src in (("fp16", R["E2"][fam]), ("T08", R["E3"][fam])):
        arms.append((ROWS[key], src["lam_m"], src["lam_m_ci"], src["uncond_tokens"], src["uncond_ci"]))
    if fam == "Llama-8B":
        s = R["E1"]["math500"]; arms.append((ROWS["self"], s["lam_m"], s["lam_m_ci"], s["uncond_tokens"], s["uncond_ci"]))
    for y, lam, lci, un, uci in arms:
        L += bar(lci[0], lci[1], y + 0.13, "blue"); L += bar(uci[0], uci[1], y - 0.13, "red")
        pts_b.append(f"({lam:.0f},{y+0.13:.2f})"); pts_r.append(f"({un:.0f},{y-0.13:.2f})")
    y = ROWS["placebo"]
    L += bar(pci[0], pci[1], y + 0.13, "black")
    L.append(f"\\addplot[only marks, mark=*, color=black, mark size=2.3pt] coordinates {{({pl},{y+0.13:.2f})}};")
    L.append(f"\\addplot[only marks, mark=*, mark options={{draw=black, fill=white}}, mark size=2.3pt] coordinates {{(0,{y-0.13:.2f})}};")
    L.append(f"\\addplot[only marks, mark=*, color=blue, mark size=2.3pt] coordinates {{{' '.join(pts_b)}}};")
    L.append(f"\\addplot[only marks, mark=*, mark options={{draw=red, fill=white}}, mark size=2.3pt] coordinates {{{' '.join(pts_r)}}};")
    return L


ytl = ", ".join(LABELS[i] for i in range(1, 8))
tex = ["% generated by analysis/gen_fig_placebo.py -- do not edit by hand", "\\begin{tikzpicture}", "\\begin{groupplot}[",
       "    group style={group size=2 by 1, horizontal sep=0.5cm, yticklabels at=edge left},",
       "    width=0.5\\linewidth, height=8.2cm,", "    xmin=-350, xmax=650, ymin=0.4, ymax=7.6,",
       f"    ytick={{1,2,3,4,5,6,7}}, yticklabels={{{ytl}}},", "    xlabel={Length change vs BF16 (tokens)},", "    xmajorgrids=true,",
       "    tick label style={font=\\small},", "]", "\\nextgroupplot[title={Qwen-7B}]"] + panel("Qwen-7B") + \
      ["\\nextgroupplot[title={Llama-8B}]"] + panel("Llama-8B") + ["\\end{groupplot}", "\\end{tikzpicture}", ""]
OUT.write_text("\n".join(tex), encoding="utf-8")
print("wrote", OUT)
