#!/usr/bin/env python3
"""LaTeX tables for the follow-up experiments (E1, E2, E3, X1) from analysis/outputs/revision2_results.json."""
import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
res = json.loads((REPO / "results" / "followup" / "reports" / "revision2_results.json").read_text())
GEN = REPO / "paper" / "v2_followups" / "generated"; GEN.mkdir(parents=True, exist_ok=True)


def sgn(x, d=0):
    s = f"{abs(x):.{d}f}"
    return ("+" if x >= 0 and float(s) != 0 else "-" if x < 0 and float(s) != 0 else "") + s


def cell(v, ci, d=0):
    return "\\vcell{$%s$}{$[%s,%s]$}" % (sgn(v, d), sgn(ci[0], d), sgn(ci[1], d))


_x = json.loads((REPO / "results" / "followup" / "reports" / "e1c_x3_results.json").read_text())
E1C = dict(acc_diff_pp=_x["E1c"]["acc_diff_pp"], acc_diff_ci=_x["E1c"]["acc_diff_ci"], uncond_tokens=_x["E1c"]["uncond_tokens"], uncond_ci=_x["E1c"]["uncond_ci"],
           lam_m=_x["E1c"]["lam_m"], lam_m_ci=_x["E1c"]["lam_m_ci"], pi_b=_x["E1c"]["placebo"], pi_ci=_x["E1c"]["placebo_ci"],
           excess_m=_x["E1c"]["excess"], excess_m_ci=_x["E1c"]["excess_ci"])
X3 = dict(acc_diff_pp=_x["X3"]["acc_diff_pp"], acc_diff_ci=_x["X3"]["acc_diff_ci"], uncond_tokens=_x["X3"]["uncond_tokens"], uncond_ci=_x["X3"]["uncond_ci"],
          lam_m=_x["X3"]["lam_cross"], lam_m_ci=_x["X3"]["lam_cross_ci"], pi_b=_x["X3"]["placebo"], pi_ci=_x["X3"]["placebo_ci"],
          excess_m=_x["X3"]["excess_cross"], excess_m_ci=_x["X3"]["excess_cross_ci"])   # X3 uses cross-seed pairs: the pre-registered criterion


def row(name, r):
    return " & ".join([name, cell(r["acc_diff_pp"], r["acc_diff_ci"], 2), cell(r["uncond_tokens"], r["uncond_ci"]),
                       cell(r["lam_m"], r["lam_m_ci"]), cell(r["pi_b"], r["pi_ci"]), cell(r["excess_m"], r["excess_m_ci"])]) + " \\\\"


L = ["% generated by analysis/gen_followup_tables.py -- do not edit by hand",
     "\\begin{table}[t]", "\\centering",
     "\\caption{Follow-up contrasts against the campaign BF16 cells (tokens; item-level 95\\% intervals, $B=10{,}000$). E2: the BF16 weights run at \\texttt{float16}. E3: BF16 sampled at $T=0.8$ instead of $0.6$. X3: Qwen BF16 with the scheduler limit \\texttt{max\\_num\\_seqs} lowered from 256 to 64, same prompts and seeds. E1: a Llama AWQ-4 checkpoint that we quantized ourselves (AutoAWQ, 4-bit, group size 128, \\texttt{zero\\_point=True}); E1c reruns it on the AWQ GEMM kernel that the community uploads use, E1 on AWQ-Marlin. The last two rows repeat the community AWQ-4 upload for reference. $^{\\ddagger}$X3 uses cross-seed pairs, the criterion fixed in advance (seed-matched pairs give $\\Lambda_b=+274$ $[+139,+422]$ and excess $+136$ $[+2,+274]$). $\\Lambda_b$: BF16-correct conditional change over seed-matched pairs (the convention of Table~\\ref{tab:placebo}); $\\Pi_b$: pooled seed placebo from the five campaign BF16 seeds ($+138$ and $+235$ on MATH-500, $+44$ on GSM8K for Llama); excess $=\\Lambda_b-\\Pi_b$ on shared item resamples. MATH-500 uses five seeds, GSM8K three. E1, E2 and E3 share the campaign prompts and sampling seeds; all 48 follow-up cells are recorded as passing the checks of Appendix~\\ref{app:followup}.}",
     "\\label{tab:followup}", "\\small", "\\resizebox{\\linewidth}{!}{%", "\\begin{tabular}{lccccc}", "\\toprule",
     "\\textbf{Contrast} & \\vcell{\\textbf{pass@1}}{$\\Delta$ (pp)} & \\vcell{\\textbf{Unconditional}}{$\\overline{\\Delta\\ell}$} & \\vcell{\\textbf{BF16-correct}}{$\\Lambda_b$} & \\vcell{\\textbf{Placebo}}{$\\Pi_b$} & \\vcell{\\textbf{Excess}}{$\\Lambda_b-\\Pi_b$} \\\\", "\\midrule",
     row("E2 Qwen, BF16 $\\to$ \\texttt{float16}", res["E2"]["Qwen-7B"]),
     row("E2 Llama, BF16 $\\to$ \\texttt{float16}", res["E2"]["Llama-8B"]), "\\midrule",
     row("E3 Qwen, $T=0.8$ vs $0.6$", res["E3"]["Qwen-7B"]),
     row("E3 Llama, $T=0.8$ vs $0.6$", res["E3"]["Llama-8B"]),
     row("X3 Qwen, \\texttt{max\\_num\\_seqs} 64 vs 256$^{\\ddagger}$", X3), "\\midrule",
     row("E1 Llama self-AWQ, MATH-500", res["E1"]["math500"]),
     row("E1 Llama self-AWQ, GSM8K", res["E1"]["gsm8k"]),
     row("E1c Llama self-AWQ, forced GEMM kernel, MATH-500", E1C),
     row("Llama community AWQ-4, MATH-500", res["E1"]["math500_community"]),
     row("Llama community AWQ-4, GSM8K", res["E1"]["gsm8k_community"]),
     "\\bottomrule", "\\end{tabular}%", "}", "\\end{table}", ""]
(GEN / "tab_followup.tex").write_text("\n".join(L), encoding="utf-8")

X = res["X1"]


def xrow(fam, name):
    x = X[fam]
    return " & ".join([name, cell(x["pi_old"], x["pi_old_ci"]), cell(x["pi_new"], x["pi_new_ci"]), cell(x["diff"], x["diff_ci"]),
                       cell(x["pi_pooled10"], x["pi_pooled10_ci"]), "interval contains 0" if x["supported"] else "interval excludes 0"]) + " \\\\"


L = ["% generated by analysis/gen_followup_tables.py -- do not edit by hand",
     "\\begin{table}[t]", "\\centering",
     "\\caption{Held-out seeds (X1). The BF16 placebo $\\Pi_b$ on MATH-500 from the five campaign seeds (42--46), from five new BF16 seeds (47--51; 20 ordered pairs each), their paired difference (same item resamples), and the placebo pooled over all ten seeds (90 ordered pairs). Item-level 95\\% intervals, $B=10{,}000$. The pre-registered rule was that the interval of the paired difference contains zero for both families.}",
     "\\label{tab:x1}", "\\small", "\\resizebox{\\linewidth}{!}{%", "\\begin{tabular}{lccccc}", "\\toprule",
     "\\textbf{Family} & \\vcell{\\textbf{Seeds 42--46}}{$\\Pi_b$} & \\vcell{\\textbf{Seeds 47--51}}{$\\Pi_b$} & \\vcell{\\textbf{Difference}}{new $-$ old} & \\vcell{\\textbf{All ten seeds}}{$\\Pi_b$} & \\textbf{Rule} \\\\", "\\midrule",
     xrow("Qwen-7B", "Qwen"), xrow("Llama-8B", "Llama"), "\\bottomrule", "\\end{tabular}%", "}", "\\end{table}", ""]
(GEN / "tab_x1.tex").write_text("\n".join(L), encoding="utf-8")
print("wrote tab_followup.tex and tab_x1.tex")
